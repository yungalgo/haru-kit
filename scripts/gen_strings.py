#!/usr/bin/env python3
"""Write the string tables of both front ends from haru_kit/apps/strings/<lang>.json.

    python scripts/gen_strings.py           # write the tables
    python scripts/gen_strings.py --check   # exit 1 if a table is not up to date

English (en.json) is the source: every other language has the same keys. A missing key falls back to English
in the apps; this script refuses keys that English does not have.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

APPS = Path(__file__).resolve().parent.parent / "haru_kit" / "apps"
STRINGS = APPS / "strings"
WEB = APPS / "web" / "src" / "i18n" / "strings.gen.ts"
MAC = APPS / "mac" / "App" / "Strings.gen.swift"
LANGUAGES = ["en", "ja", "zh", "ko", "es", "fr", "de", "pt", "ru"]
HEADER = "Generated by scripts/gen_strings.py from haru_kit/apps/strings/*.json. Do not edit."


def load() -> dict[str, dict[str, str]]:
    """The tables; keys in pending-*.json (English only, not yet translated) are added to English."""
    tables = {lang: json.loads((STRINGS / f"{lang}.json").read_text(encoding="utf-8")) for lang in LANGUAGES}
    for pending in sorted(STRINGS.glob("pending-*.json")):
        for key, text in json.loads(pending.read_text(encoding="utf-8")).items():
            tables["en"].setdefault(key, text)
    tables["en"] = dict(sorted(tables["en"].items()))
    keys = set(tables["en"])
    for lang, table in tables.items():
        extra = set(table) - keys
        if extra:
            raise SystemExit(f"{lang}.json has keys that en.json does not have: {sorted(extra)}")
    return tables


def swift_literal(text: str) -> str:
    return ('"' + text.replace("\\", "\\\\").replace('"', '\\"')
            .replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t") + '"')


def web_source(tables: dict[str, dict[str, str]]) -> str:
    lines = [f"// {HEADER}", "", "export const en = " + json.dumps(tables["en"], ensure_ascii=False, indent=2) + ";",
             "", "export type Key = keyof typeof en;", "export type Strings = Partial<Record<Key, string>>;", "",
             "export const tables: Record<string, Strings> = {", "  en,"]
    for lang in LANGUAGES[1:]:
        lines.append(f"  {lang}: " + json.dumps(tables[lang], ensure_ascii=False, indent=2).replace("\n", "\n  ") + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def mac_source(tables: dict[str, dict[str, str]]) -> str:
    lines = [f"// {HEADER}", "", "let uiStrings: [String: [String: String]] = ["]
    for lang in LANGUAGES:
        lines.append(f'    "{lang}": [')
        for key, text in tables[lang].items():
            lines.append(f"        {swift_literal(key)}: {swift_literal(text)},")
        lines.append("    ],")
    lines.append("]")
    return "\n".join(lines) + "\n"


def main() -> int:
    tables = load()
    outputs = {WEB: web_source(tables), MAC: mac_source(tables)}
    if "--check" in sys.argv:
        stale = [str(path) for path, text in outputs.items()
                 if not path.is_file() or path.read_text(encoding="utf-8") != text]
        if stale:
            print("Out of date (run scripts/gen_strings.py):", *stale, sep="\n  ")
            return 1
        return 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(APPS.parent.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
